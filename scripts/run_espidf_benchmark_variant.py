"""
Flash a specific TFLite model into the native ESP-IDF benchmark and run repeats.
"""

from __future__ import annotations

import argparse
import subprocess
import sys
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
IDF_ROOT = ROOT / ".external" / "esp-idf-v5.4.2"
IDF_PROJECT = ROOT / "espidf_firmware" / "dbs_espnn_benchmark"
MODEL_HEADER = IDF_PROJECT / "main" / "dbs_model_data.h"
BENCH_CONFIG_HEADER = IDF_PROJECT / "main" / "dbs_benchmark_config.h"
REPEAT_HELPER = ROOT / "scripts" / "repeat_esp32_benchmark.py"
CONVERT_HELPER = ROOT / "deployment" / "convert_tflite_to_c.py"


def _run(command: str, cwd: Path) -> None:
    result = subprocess.run(command, cwd=cwd, shell=True, text=True)
    if result.returncode != 0:
        raise SystemExit(result.returncode)


def _default_tensor_arena_bytes(model_path: Path) -> int:
    size_bytes = model_path.stat().st_size
    if size_bytes > 256 * 1024:
        return 128 * 1024
    if size_bytes > 64 * 1024:
        return 64 * 1024
    return 16 * 1024


def _write_benchmark_config(*, runs: int, warmup_runs: int = 20, tensor_arena_bytes: int) -> None:
    if runs <= 0:
        raise SystemExit(f"--runs must be positive, got {runs}")
    if warmup_runs < 0:
        raise SystemExit(f"warmup_runs must be non-negative, got {warmup_runs}")
    if tensor_arena_bytes <= 0:
        raise SystemExit(f"tensor_arena_bytes must be positive, got {tensor_arena_bytes}")

    BENCH_CONFIG_HEADER.write_text(
        "#pragma once\n\n"
        "// Generated by scripts/run_espidf_benchmark_variant.py\n"
        f"#define DBS_BENCHMARK_WARMUP_RUNS {warmup_runs}UL\n"
        f"#define DBS_BENCHMARK_RUNS {runs}UL\n"
        f"#define DBS_TENSOR_ARENA_SIZE_BYTES {tensor_arena_bytes}UL\n"
    )


def main() -> int:
    parser = argparse.ArgumentParser(description="Flash a TFLite model into the native ESP-IDF benchmark and repeat runs.")
    parser.add_argument("--model-path", required=True)
    parser.add_argument("--label", required=True)
    parser.add_argument("--port", required=True)
    parser.add_argument("--repeats", type=int, default=5)
    parser.add_argument("--runs", type=int, default=200)
    parser.add_argument("--timeout", type=float, default=15.0)
    parser.add_argument("--out-dir", default="results/esp32/repeats")
    parser.add_argument(
        "--tensor-arena-bytes",
        type=int,
        default=None,
        help="Override the native ESP-IDF tensor arena size. Defaults to a size-based heuristic.",
    )
    args = parser.parse_args()

    model_path = Path(args.model_path).expanduser().resolve()
    if not model_path.exists():
        raise SystemExit(f"Missing model: {model_path}")

    tensor_arena_bytes = (
        int(args.tensor_arena_bytes)
        if args.tensor_arena_bytes is not None
        else _default_tensor_arena_bytes(model_path)
    )

    convert_cmd = (
        f"{sys.executable} {CONVERT_HELPER} "
        f"--tflite-path {model_path} --output-path {MODEL_HEADER} --var-name dbs_model"
    )
    _run(convert_cmd, ROOT)
    _write_benchmark_config(runs=args.runs, tensor_arena_bytes=tensor_arena_bytes)
    print(
        f"[OK] Native benchmark config: runs={args.runs}, tensor_arena_bytes={tensor_arena_bytes}",
        flush=True,
    )

    idf_env = (
        f"export IDF_PATH={IDF_ROOT} "
        f"IDF_PATH_FORCE=1 "
        f"IDF_TOOLS_PATH={ROOT / '.external' / '.espressif'} "
        f"IDF_PYTHON_ENV_PATH={ROOT / '.external' / '.idf-python-env'}"
    )
    flash_cmd = (
        f"{idf_env} && "
        f"source {IDF_ROOT / 'export.sh'} >/dev/null && "
        f"idf.py -p {args.port} build flash"
    )
    _run(flash_cmd, IDF_PROJECT)

    repeat_cmd = (
        f"{sys.executable} {REPEAT_HELPER} "
        f"--mode legacy --port {args.port} --repeats {args.repeats} "
        f"--runs {args.runs} --timeout {args.timeout} "
        f"--label {args.label} --out-dir {args.out_dir}"
    )
    _run(repeat_cmd, ROOT)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
